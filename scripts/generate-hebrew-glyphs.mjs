// Generates src/data/hebrew-glyphs.ts: the Hebrew name of each sephirah as a
// single SVG path, so the site never loads a Hebrew font.
//
// Font: Noto Sans Hebrew (SIL Open Font License 1.1), weight 300.
// Run with the two generator-only packages installed ad hoc:
//   npx -y -p opentype.js -p @fontsource/noto-sans-hebrew node scripts/generate-hebrew-glyphs.mjs
// (or `npm i --no-save opentype.js @fontsource/noto-sans-hebrew` first).
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js');
const fontFile =
  require.resolve('@fontsource/noto-sans-hebrew/files/noto-sans-hebrew-hebrew-300-normal.woff');
const font = opentype.parse(readFileSync(fontFile));

const names = {
  keter: 'כתר',
  chokhmah: 'חכמה',
  binah: 'בינה',
  daat: 'דעת',
  chesed: 'חסד',
  gevurah: 'גבורה',
  tiferet: 'תפארת',
  netzach: 'נצח',
  hod: 'הוד',
  yesod: 'יסוד',
  malkuth: 'מלכות',
};

const SIZE = 100;
const r = (n) => Math.round(n * 10) / 10;

// opentype.js's own toPathData() emits NaN on some contours; serialize by hand.
function toPathData(commands) {
  return commands
    .map((c) => {
      switch (c.type) {
        case 'M':
        case 'L':
          return `${c.type}${r(c.x)} ${r(c.y)}`;
        case 'Q':
          return `Q${r(c.x1)} ${r(c.y1)} ${r(c.x)} ${r(c.y)}`;
        case 'C':
          return `C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${r(c.x)} ${r(c.y)}`;
        case 'Z':
          return 'Z';
        default:
          throw new Error(`Unexpected path command ${c.type}`);
      }
    })
    .join('');
}
const out = {};
for (const [id, word] of Object.entries(names)) {
  // opentype.js lays glyphs out left to right: reverse to get correct RTL order.
  // None of these words uses final letter forms, so no shaping is needed.
  const visual = [...word].reverse().join('');
  const path = font.getPath(visual, 0, 0, SIZE);
  const box = path.getBoundingBox();
  // Normalize: origin at the glyph run's top-left corner.
  for (const cmd of path.commands) {
    for (const k of ['x', 'x1', 'x2']) if (typeof cmd[k] === 'number') cmd[k] -= box.x1;
    for (const k of ['y', 'y1', 'y2']) if (typeof cmd[k] === 'number') cmd[k] -= box.y1;
  }
  out[id] = {
    word,
    d: toPathData(path.commands),
    width: Math.round(box.x2 - box.x1),
    height: Math.round(box.y2 - box.y1),
  };
}

const body = Object.entries(out)
  .map(
    ([id, g]) =>
      `  ${id}: {\n    word: '${g.word}',\n    width: ${g.width},\n    height: ${g.height},\n    d: '${g.d}',\n  },`,
  )
  .join('\n');

writeFileSync(
  new URL('../src/data/hebrew-glyphs.ts', import.meta.url),
  `// Generated by scripts/generate-hebrew-glyphs.mjs — do not edit by hand.
// Glyph outlines from Noto Sans Hebrew (SIL Open Font License 1.1).
import type { Sephirah } from './sephirot';

export interface HebrewGlyph {
  word: string;
  width: number;
  height: number;
  d: string;
}

export const hebrewGlyphs: Record<Sephirah, HebrewGlyph> = {
${body}
};
`,
);
console.log('wrote src/data/hebrew-glyphs.ts');
